const fs = require('fs')
const path = require('path')

// Load environment variables from .env file
// eslint-disable-next-line import/no-extraneous-dependencies
require('dotenv').config({ path: path.join(__dirname, '../.env') })

// Import whitelabel colors from CJS source file
const whitelabelColors = require('../src/consts/whitelabelColors.config.cjs')

/**
 * Converts camelCase to kebab-case
 */
function camelToKebab(str) {
  return str.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}

/**
 * Generates SCSS variable overrides for a specific whitelabel
 */
function generateScssOverrides(whitelabelName) {
  const colors = whitelabelColors[whitelabelName]

  if (!colors) {
    return null
  }

  let scss = `// Auto-generated whitelabel color overrides for: ${whitelabelName}\n`
  scss += `// Generated at: ${new Date().toISOString()}\n`
  scss += `// DO NOT EDIT THIS FILE MANUALLY - Changes will be overwritten\n\n`

  Object.keys(colors).forEach(key => {
    const value = colors[key]
    if (value) {
      const scssVarName = camelToKebab(key)
      scss += `$${scssVarName}: ${value};\n`
    }
  })

  return scss
}

// Main execution
const whitelabel = process.env.VITE_APP_WHITELABEL || 'educacross'

const scssContent = generateScssOverrides(whitelabel)

if (scssContent) {
  const outputPath = path.join(__dirname, '../src/assets/scss/variables/_whitelabel-colors.scss')
  fs.writeFileSync(outputPath, scssContent, 'utf8')
} else {
  process.exit(1)
}
